import Foundation
import AppKit
import os

/// High-efficiency pasteboard monitor with privacy-marker detection and exclusion rules.
public final class ClipboardWatcher: @unchecked Sendable {
    public static let shared = ClipboardWatcher()

    private let logger = Logger(subsystem: "com.privaclip.app", category: "watcher")
    private let lock = NSLock()

    // MARK: - Privacy & Sensitive Markers
    private static let sensitivePasteboardTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.keeweb.keeweb")
    ]

    // Supported rich text representations
    public static let richTextTypes: [NSPasteboard.PasteboardType] = [
        .rtf,
        .rtfd,
        .html,
        NSPasteboard.PasteboardType("public.utf16-plain-text"),
        NSPasteboard.PasteboardType("public.utf16-external-plain-text")
    ]

    // Caps
    public static let maxTextCharacters = 100_000
    public static let maxRichBytes = 500_000
    public static let maxImageBytes = 25_000_000

    private var timer: Timer?
    private var lastChangeCount: Int = -1
    private var suppressedChangeCount: Int = -1
    private var lastStoredText: String?
    private var lastStoredImageHash: String?
    private var onCaptured: (@Sendable (CapturedContent) -> Void)?

    public init() {}

    deinit {
        stop()
    }

    /// Suppresses processing of the next change event if triggered by PrivaClip itself.
    public func suppressNextChange() {
        lock.lock()
        defer { lock.unlock() }
        suppressedChangeCount = NSPasteboard.general.changeCount
    }

    /// Starts polling the system pasteboard.
    public func start(handler: @escaping @Sendable (CapturedContent) -> Void) {
        lock.lock()
        self.onCaptured = handler
        self.lastChangeCount = NSPasteboard.general.changeCount
        lock.unlock()

        stop()

        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            self?.checkPasteboard()
        }
        RunLoop.main.add(t, forMode: .common)
        self.timer = t

        DispatchQueue.main.async { [weak self] in
            self?.checkPasteboard()
        }
    }

    /// Stops clipboard monitoring.
    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Manually trigger check (useful in unit testing).
    public func checkPasteboard() {
        let pb = NSPasteboard.general
        let changeCount = pb.changeCount

        lock.lock()
        if changeCount == lastChangeCount || changeCount == suppressedChangeCount {
            lock.unlock()
            return
        }
        lastChangeCount = changeCount
        lock.unlock()

        let types = pb.types ?? []

        // 1. Honor privacy markers (password managers, ephemeral tokens)
        for sensitive in Self.sensitivePasteboardTypes {
            if types.contains(sensitive) {
                logger.info("Skipped clipboard item bearing sensitive marker \(sensitive.rawValue, privacy: .public)")
                return
            }
        }

        // 2. Resolve source application
        let (bundleID, appName) = ApplicationTracker.currentSourceApp()

        // 3. Honor application exclusion rules
        if let bundleID, AppPreferences.shared.excludedBundleIDs.contains(bundleID) {
            logger.info("Skipped copy from excluded application: \(bundleID, privacy: .public)")
            return
        }

        // 4. Capture plain text if present
        var rawText: String?
        if let str = pb.string(forType: .string) {
            rawText = str
        } else if let strings = pb.readObjects(forClasses: [NSString.self], options: nil) as? [NSString],
                  let first = strings.first {
            rawText = first as String
        }

        if let raw = rawText {
            let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return }

            lock.lock()
            if trimmed == lastStoredText {
                lock.unlock()
                return
            }
            lastStoredText = trimmed
            lastStoredImageHash = nil
            lock.unlock()

            let storedText: String
            if raw.count > Self.maxTextCharacters {
                storedText = String(raw.prefix(Self.maxTextCharacters)) + "\n\n[…truncated by PrivaClip]"
            } else {
                storedText = raw
            }

            // Capture rich text representations
            var richReps: [String: Data] = [:]
            var totalRichSize = 0
            for rType in Self.richTextTypes where types.contains(rType) {
                if let data = pb.data(forType: rType) {
                    totalRichSize += data.count
                    richReps[rType.rawValue] = data
                }
            }
            let reps: [String: Data]? = (totalRichSize <= Self.maxRichBytes && !richReps.isEmpty) ? richReps : nil

            onCaptured?(.text(
                plain: storedText,
                richReps: reps,
                bundleID: bundleID,
                appName: appName
            ))
            return
        }

        // 5. Capture image if present
        if let (pngData, width, height) = Self.extractImage(from: pb) {
            guard pngData.count <= Self.maxImageBytes else {
                logger.info("Skipped image: size \(pngData.count) exceeds 25 MB cap.")
                return
            }

            let hash = CryptoService.sha256Hex(pngData)
            lock.lock()
            if hash == lastStoredImageHash {
                lock.unlock()
                return
            }
            lastStoredImageHash = hash
            lastStoredText = nil
            lock.unlock()

            onCaptured?(.image(
                pngData: pngData,
                width: width,
                height: height,
                bundleID: bundleID,
                appName: appName
            ))
        }
    }

    private static func extractImage(from pb: NSPasteboard) -> (Data, Int, Int)? {
        if let png = pb.data(forType: .png), let rep = NSBitmapImageRep(data: png) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        if let tiff = pb.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        return nil
    }
}
